export interface TileDef {
  key: string;
  art: Art;
  /** Which named ramp this tile's four indices resolve to. */
  swatch: SwatchName;
  /** Blocks movement entirely. */
  solid?: boolean;
  /** Wild encounters can trigger when standing here. */
  encounter?: boolean;
  /** Can only be entered by hopping down from above. */
  ledge?: boolean;
}

